// Derives the desktop (SQLite) Prisma schema from the canonical MySQL schema,
// so there is a single source of truth: backend/prisma/schema.prisma.
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..')
const src = path.join(root, 'backend', 'prisma', 'schema.prisma')
const outDir = path.join(root, 'backend', 'prisma', 'sqlite')
const out = path.join(outDir, 'schema.prisma')

let schema = fs.readFileSync(src, 'utf8')
schema = schema.replace(/provider\s*=\s*"mysql"/, 'provider = "sqlite"')
schema = schema.replace(/\s@db\.\w+(\([^)]*\))?/g, '')       // MySQL-only column types
schema = schema.replace(/(@@?(?:index|unique)\([^)]*?),\s*length:\s*\d+/g, '$1') // index prefix lengths
if (/provider = "mysql"/.test(schema)) throw new Error('Conversion failed')

fs.mkdirSync(outDir, { recursive: true })
fs.writeFileSync(out, `// GENERATED by desktop/scripts/make-sqlite-schema.mjs — do not edit.\n${schema}`)
console.log(`SQLite schema written to ${path.relative(root, out)}`)
